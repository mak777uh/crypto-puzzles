def decode(raw):
    bits = "".join(c for c in raw if c in "01")
    n = len(bits) // 8
    data = bytes(int(bits[i:i + 8], 2) for i in range(0, n * 8, 8))
    return bytes(int("{:08b}".format(b)[::-1], 2) for b in data)[::-1]


