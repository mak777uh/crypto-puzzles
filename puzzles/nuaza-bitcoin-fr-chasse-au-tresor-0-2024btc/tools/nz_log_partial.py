# -*- coding: utf-8 -*-
"""Атомарная дозапись в LOG.md Nuaza: чексуммный фильтр nz_partial + ноги E/E2 оракула."""
import os
import tempfile
from pathlib import Path

D = Path(__file__).resolve().parents[1]
LOG = D / "LOG.md"
MARKER = "чексуммный фильтр `tools/nz_partial.py`"

BLOCK = """
## 2026-10-19, 13:37 UTC — Qoder — чексуммный фильтр и ветка приватного ключа
- `tools/nz_partial.py` — **новый инструмент**: когда часть слов известна, а часть читается
  неоднозначно (объект на иллюстрации можно прочесть двумя способами), фильтр перебирает
  комбинации кандидатов и оставляет только **валидные по чексумме BIP39**. 8 бит чексуммы при
  11 битах слова = ложное прохождение ~1/256, поэтому 2 неоднозначных слота (4,19 млн комбинаций)
  сжимаются до ~16 тысяч строк, а 1 слот из 2 кандидатов даёт почти всегда ровно одну строку.
  Спецификация слотов: `1=corde;2=mer|bateau;17=pierre;22=en:open;23=en:always;24=en:win`
  («any» = полный список; `--derive` дополнительно выводит BIP84-адрес каждого выжившего и сравнивает
  с целью; `--limit` по умолчанию 5 000 000 и отказывает до старта, если комбинаций больше).
- Сертификация `python tools/nz_partial.py --selftest` → `SELFTEST OK`, 4 ноги (случайные честные
  24-словные фразы, генерируются из 32 случайных байт энтропии, истинная фраза известна заранее):
  [A] при 2 скрытых слотах истинная фраза оказывается в списке (survivors 16 412/16 547 при
  ожидании 16 384 ± 128 — статистика сходится), [B] из пары «истинный кандидат + подставной»
  чексумму проходит 1 и это истинный, [B2] из ~1000 случайных ложных кандидатов прошли 8
  (ожидание ~4, то есть сила фильтра измерена, а не заявлена), [C] если одно **фиксированное**
  слово неверно, истинная фраза в списке не появляется (0 ложных восстановлений) при том, что сам
  список остаётся правдоподобным (16 088 строк) — честное предупреждение: фильтр снимает
  неоднозначность чтения, но не ошибку в другом слове.
- `tools/nz_oracle.py --selftest` расширен до **шести** ног: добавлены [E] приватный ключ официального
  BIP84-вектора на `m/84'/0'/0'/0/0` = `4604b4b7…74ce4fa3` (совпал с опубликованным вектором BIP84)
  и [E2] наш собственный Base58Check/WIF (реализация в файле, независимая) == `WifEncoder` из
  bip_utils. То есть сертифицирована не только ветка «seed → адрес», но и ветка «seed → ключ»,
  которая понадобится в момент успеха.
- При точном совпадении с адресом цели оракул печатает seed, raw-ключ и WIF **только в stdout** и
  явно напоминает: в репозиторий ничего не сохранять, передать лично Илье, вывод средств — только по
  его отдельному письменному команду. Файл `data/nz_partial_HIT.json` не создаётся, пока нет
  совпадения.
- Статус цели без изменений: `bc1q8zfy6wvvtskzkg4s343x42pyf363nmejspgc02`, 20 240 000 сат,
  0 потрачено. Блокер — файл книги (см. предыдущую запись). Транзакций, трат, писем, публикаций нет.
"""


def main():
    data = LOG.read_bytes()
    if MARKER.encode("utf-8") in data:
        print("уже записано, пропуск")
        return
    if not data.endswith(b"\n"):
        data += b"\n"
    data += BLOCK.encode("utf-8")
    fd, tmp = tempfile.mkstemp(dir=str(LOG.parent), prefix=".nzlog2_", suffix=".md")
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, LOG)
    finally:
        if os.path.exists(tmp):
            os.remove(tmp)
    print("LOG.md:", len(data), "байт")


if __name__ == "__main__":
    main()
